// SQL keyword tables for the catalog-anchored scanner. The reserved
// set spans the common dialects (ANSI, Postgres, MySQL, BigQuery,
// Snowflake, T-SQL) so bare identifiers that are really keywords are
// never emitted as catalog candidates. No vscode imports.

/**
 * Keywords that put the *next* identifier chain in table position:
 * FROM x, JOIN x, INSERT INTO x, MERGE INTO x, UPDATE x,
 * CREATE/ALTER/DROP TABLE x, USING x.
 */
export const TABLE_TRIGGER_KEYWORDS: ReadonlySet<string> = new Set([
  "FROM",
  "JOIN",
  "INTO",
  "UPDATE",
  "TABLE",
  "USING",
]);

/**
 * Keywords that may legitimately sit between a WITH-list element and
 * the next CTE name without ending the WITH clause
 * (`WITH RECURSIVE x AS NOT MATERIALIZED (...)`).
 */
export const WITH_LIST_KEYWORDS: ReadonlySet<string> = new Set([
  "AS",
  "RECURSIVE",
  "NOT",
  "MATERIALIZED",
]);

